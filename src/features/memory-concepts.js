// 词 → 概念（反向索引，建一次）
const WORD2CONCEPTS = (() => {
  const m = new Map()
  for (const [c, list] of Object.entries(CONCEPTS)) {
    for (const w of list) {
      if (!m.has(w)) m.set(w, new Set())
      m.get(w).add(c)
    }
  }
  return m
})()

/** 一段文字涉及哪些概念（集合）。 */
export function conceptsOf(text) {
  const s = String(text || '').toLowerCase()
  const hit = new Set()
  // 词表先按长度降序匹配，避免「学日语」被「日语」抢先
  for (const w of WORD2CONCEPTS.keys()) if (s.includes(w)) for (const c of WORD2CONCEPTS.get(w)) hit.add(c)
  return hit
}

/** 查询扩展：给查询补概念词，BM25 能吃到重叠。返回追加词列表。 */
export function expandQuery(query, { maxExtra = 6 } = {}) {
  const cs = conceptsOf(query)
  if (!cs.size) return []
  const extra = []
  for (const c of cs) {
    // 概念名本身通常也是关键词（工作/生日/宠物），加上即可让记忆条目里的「上班/猫/生日」同概念命中
    extra.push(c)
  }
  return extra.slice(0, maxExtra)
}
